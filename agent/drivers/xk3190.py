"""Драйвер семейства Yaohua XK3190 (DS3 — СВХ «Кокчо-Коз»; D2+ — ПЗТК «Беловодское»).

Кадр порта XK3190-DS3 совпадает с протоколом «VESAR» байт в байт:
STX, знак, 7 цифр ASCII, XOR-КС двумя hex-символами, ETX. Подтверждено
буфером «Менеджера сервера весов АВТО» на Кокчо-Козе 03.09.2026 —
``02 2B 30 30 30 30 30 30 30 31 42 03`` (пустые весы; XOR «+» и семи
нулей = 0x1B). Отличается только трактовка цифр: индикатор шлёт ЦЕЛЫЕ
килограммы (в ВесыСофт «Делить на: 1»), дискрета табло — 20 кг.
Поэтому драйвер — VesarDriver с другими умолчаниями; на объекте с иной
дискретой оба параметра переопределяются в конфиге агента
(``[scale] weight_divisor`` / ``discrete_kg``).
"""

from agent.drivers.vesar import VesarDriver


class Xk3190Driver(VesarDriver):
    """XK3190: кадр VESAR, цифры — целые кг, дискрета 20 кг."""

    DEFAULT_WEIGHT_DIVISOR: float = 1.0
    DEFAULT_DISCRETE_KG: float = 20.0
