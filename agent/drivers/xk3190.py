"""Драйвер семейства Yaohua XK3190 (DS3 — СВХ «Кокчо-Коз»; D2+ — ПЗТК «Беловодское»).

Кадр порта XK3190-DS3 совпадает с протоколом «VESAR» байт в байт:
STX, знак, 7 цифр ASCII, XOR-КС двумя hex-символами, ETX. Подтверждено
буфером «Менеджера сервера весов АВТО» на Кокчо-Козе 03.09.2026 —
``02 2B 30 30 30 30 30 30 30 31 42 03`` (пустые весы; XOR «+» и семи
нулей = 0x1B). Цифры — ДЕСЯТЫЕ кг, как у VESAR (урок первого запуска
03.09.2026: человек 80 кг показался как 800 при делителе 1 — настройка
«Делить на: 1» в ВесыСофт к трактовке кадра отношения не имеет; в 0.4.27
умолчание было 1, исправлено в 0.4.28). Отличие от VESAR — только дискрета
табло 20 кг. Поэтому драйвер — VesarDriver с другой дискретой; на объекте
с иной трактовкой оба параметра переопределяются в конфиге агента
(``[scale] weight_divisor`` / ``discrete_kg``).
"""

from agent.drivers.vesar import VesarDriver


class Xk3190Driver(VesarDriver):
    """XK3190: кадр VESAR, цифры — десятые кг, дискрета 20 кг."""

    DEFAULT_WEIGHT_DIVISOR: float = 10.0
    DEFAULT_DISCRETE_KG: float = 20.0
